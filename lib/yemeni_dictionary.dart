  static String normalizeYemeniText(String input) {
    String text = input.trim();
    financialSynonyms.forEach((yemeniTerm, standardTerm) {
      if (text.contains(yemeniTerm)) {
        text = text.replaceAll(yemeniTerm, standardTerm);
      }
    });
    return text;
  }
